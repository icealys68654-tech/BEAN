param(
  [Parameter(Mandatory=$false)]
  [string]$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\\..")).Path,

  [Parameter(Mandatory=$false)]
  [switch]$SkipDocker
)

$ErrorActionPreference = "Stop"
$script:Failures = 0
$script:Warnings = 0

function Write-Check {
  param([string]$Name, [bool]$Passed, [string]$Detail, [switch]$Warning)
  if ($Passed) {
    Write-Host "[PASS] $Name - $Detail" -ForegroundColor Green
  } elseif ($Warning) {
    $script:Warnings++
    Write-Host "[WARN] $Name - $Detail" -ForegroundColor Yellow
  } else {
    $script:Failures++
    Write-Host "[FAIL] $Name - $Detail" -ForegroundColor Red
  }
}

function Read-DotEnv {
  param([string]$Path)
  $values = @{}
  foreach ($line in Get-Content -LiteralPath $Path) {
    $trimmed = $line.Trim()
    if (-not $trimmed -or $trimmed.StartsWith("#")) { continue }
    if ($trimmed -match '^([A-Za-z_][A-Za-z0-9_]*)=(.*)$') {
      $values[$matches[1]] = $matches[2].Trim().Trim('"').Trim("'")
    }
  }
  return $values
}

try {
  $RepoRoot = (Resolve-Path -LiteralPath $RepoRoot).Path
  Push-Location $RepoRoot
  try {
    Write-Host "BEAN deployment preflight"
    Write-Host "Repository: $RepoRoot"
    Write-Host "Identity: $([Security.Principal.WindowsIdentity]::GetCurrent().Name)"
    Write-Host ""

    $requiredFiles = @(
      ".env",
      "docker-compose.yml",
      "Dockerfile",
      "deploy/Caddyfile",
      "ops/windows/Start-Bean.ps1",
      "ops/windows/Backup-TagEngine.ps1",
      "ops/windows/Register-BeanTasks.ps1",
      "ops/windows/ids_ingest.py"
    )
    foreach ($relative in $requiredFiles) {
      Write-Check "File $relative" (Test-Path -LiteralPath (Join-Path $RepoRoot $relative) -PathType Leaf) "Required deployment file is present."
    }

    $envPath = Join-Path $RepoRoot ".env"
    if (Test-Path -LiteralPath $envPath -PathType Leaf) {
      $envValues = Read-DotEnv -Path $envPath
      $requiredKeys = @(
        "ENTEC_API_TOKEN", "ENTEC_DASHBOARD_TOKEN",
        "BEAN_DASHBOARD_DOMAIN", "BEAN_API_DOMAIN",
        "BEAN_TLS_EMAIL", "ENTEC_PROXY_USER",
        "ENTEC_PROXY_PASSWORD_HASH"
      )
      foreach ($key in $requiredKeys) {
        $present = $envValues.ContainsKey($key) -and -not [string]::IsNullOrWhiteSpace($envValues[$key])
        Write-Check "Environment $key" $present "Required .env value is set."
        if ($present -and $envValues[$key] -match '^(replace-with|CHANGE_ME|TODO)') {
          Write-Check "Environment $key placeholder" $false "Replace the example placeholder before deployment."
        }
      }

      foreach ($key in @("ENTEC_API_TOKEN", "ENTEC_DASHBOARD_TOKEN")) {
        if ($envValues.ContainsKey($key)) {
          $value = $envValues[$key]
          Write-Check "$key strength" ($value.Length -ge 32 -and $value -notmatch '^(replace-with|CHANGE_ME|TODO)') "Token must be at least 32 characters and not an example value."
        }
      }

      $apiToken = [string]$envValues["ENTEC_API_TOKEN"]
      $dashboardToken = [string]$envValues["ENTEC_DASHBOARD_TOKEN"]
      if ($apiToken -and $dashboardToken) {
        Write-Check "Token separation" ($apiToken -cne $dashboardToken) "API and dashboard tokens must be different."
      }

      $dashboardDomain = [string]$envValues["BEAN_DASHBOARD_DOMAIN"]
      $apiDomain = [string]$envValues["BEAN_API_DOMAIN"]
      if ($dashboardDomain -and $apiDomain) {
        Write-Check "Distinct public hostnames" ($dashboardDomain -ne $apiDomain) "Dashboard and API hostnames must differ."
        Write-Check "Example hostname replacement" ($dashboardDomain -notmatch 'example\\.com$' -and $apiDomain -notmatch 'example\\.com$') "Replace example.com with hostnames you control."
      }

      $hash = [string]$envValues["ENTEC_PROXY_PASSWORD_HASH"]
      if ($hash) {
        Write-Check "Caddy password hash" ($hash -match '^\\$2[aby]\\$') "Expected a bcrypt hash generated by caddy hash-password."
      }

      $email = [string]$envValues["BEAN_TLS_EMAIL"]
      if ($email) {
        Write-Check "TLS contact email" ($email -match '^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$') "Provide a valid ACME contact email."
      }
    } else {
      Write-Check ".env configuration" $false "Copy .env.example to .env and populate production values."
    }

    foreach ($relative in @("data/snapshots", "backups")) {
      $directory = Join-Path $RepoRoot $relative
      if (-not (Test-Path -LiteralPath $directory)) {
        try { New-Item -ItemType Directory -Path $directory -Force | Out-Null } catch {}
      }
      $writable = Test-Path -LiteralPath $directory -PathType Container
      if ($writable) {
        try {
          $probe = Join-Path $directory (".bean-preflight-" + [guid]::NewGuid().ToString("N"))
          [IO.File]::WriteAllText($probe, "preflight")
          Remove-Item -LiteralPath $probe -Force
        } catch { $writable = $false }
      }
      Write-Check "Writable $relative" $writable "Current account can create and remove a test file."
    }

    if (-not $SkipDocker) {
      $dockerCommand = Get-Command docker -ErrorAction SilentlyContinue
      Write-Check "Docker CLI" ($null -ne $dockerCommand) "docker executable is available."
      if ($null -ne $dockerCommand) {
        & $dockerCommand.Source info *> $null
        $engineReady = ($LASTEXITCODE -eq 0)
        Write-Check "Docker Engine" $engineReady "Current account can query the Docker daemon."
        & $dockerCommand.Source compose version *> $null
        $composeReady = ($LASTEXITCODE -eq 0)
        Write-Check "Docker Compose" $composeReady "Compose plugin is available."
        if ($composeReady -and (Test-Path -LiteralPath $envPath -PathType Leaf)) {
          & $dockerCommand.Source compose config --quiet *> $null
          Write-Check "Compose configuration" ($LASTEXITCODE -eq 0) "docker compose config --quiet validates the deployment configuration."
        } else {
          Write-Check "Compose configuration" $false "Requires Docker Compose and a populated .env file."
        }
      }
    } else {
      Write-Check "Docker checks" $true "Skipped by request."
    }

    foreach ($taskName in @("BEAN Container Startup", "BEAN TagEngine Daily Backup")) {
      $task = Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
      if ($null -eq $task) {
        Write-Check "Scheduled task $taskName" $false "Task is not registered yet." -Warning
      } else {
        $principalName = [string]$task.Principal.UserId
        Write-Check "Scheduled task $taskName" $true "Registered with principal $principalName."
        if ($principalName -eq "SYSTEM") {
          Write-Check "SYSTEM Docker access ($taskName)" $false "Preflight runs as the current account; validate Docker daemon access under SYSTEM separately." -Warning
        }
      }
    }
  } finally {
    Pop-Location
  }
} catch {
  Write-Check "Preflight execution" $false $_.Exception.Message
}

Write-Host ""
Write-Host ("Preflight result: {0} failure(s), {1} warning(s)." -f $script:Failures, $script:Warnings)
if ($script:Failures -gt 0) {
  exit 1
}
exit 0
